"""Generate/check DOM element types from the three page templates, without changing HTML."""

from __future__ import annotations

import argparse
from html.parser import HTMLParser
from pathlib import Path


class Elements(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.elements: dict[str, str] = {}

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        identifier = dict(attrs).get("id")
        if identifier and "${" not in identifier and tag != "svg":
            if identifier in self.elements:
                raise ValueError(f"Duplicate element id: {identifier}")
            self.elements[identifier] = tag


def generated_types(root: Path) -> str:
    lines = ["// Generated by scripts/web_types.py from HTML; do not edit by hand."]
    for page, name in (("index", "CleanElements"), ("studio", "StudioElements"), ("voicelab", "VoiceLabElements")):
        parser = Elements()
        parser.feed((root / f"src/naturalvoice/web/{page}.html").read_text())
        lines.append(f"export interface {name} {{")
        for identifier, tag in sorted(parser.elements.items()):
            key = f"#{identifier}" if page == "index" else identifier
            lines.append(f'  "{key}": HTMLElementTagNameMap["{tag}"];')
        lines.append("}")
    lines.append("export type ElementFor<M, K extends string> = K extends keyof M ? M[K] : HTMLElement;")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate the checked-in declarations")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "types/dom.d.ts"
    expected = generated_types(root)
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected)
    elif not target.exists() or target.read_text() != expected:
        raise SystemExit("DOM types are stale. Run uv run python scripts/web_types.py --write")
    else:
        print("DOM declarations match the HTML templates.")


if __name__ == "__main__":
    main()
